"""版本号的唯一来源。

为什么一个查证工具需要版本号：这套东西的主张是「同一批输入永远得到同一个标签」。
但只要置信度门槛、权重系数、词表其中任何一项改过，同一个问题就会得出不同的卡。
没有版本号时，两张不一样的卡说不清是「数据变了」还是「代码变了」——这正是可复现性最后缺的一块。

所以版本号会：
  · 写进每张查证卡的 JSON（`card.version`）和静态卡的页脚
  · 显示在网页页脚、命令行表头
  · 由 `/api/health` 返回，便于脚本核对部署的是哪一版
  · 出现在 HTTP 响应头 `Server: DetectiveAgent/<version>`

改判定逻辑（阈值、权重、词表、规则）→ 升 MINOR；
只改文案、样式、文档 → 升 PATCH；
换架构或改变卡片结构（字段增删）→ 升 MAJOR。
"""

